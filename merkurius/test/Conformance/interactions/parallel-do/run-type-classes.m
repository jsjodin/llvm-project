% OUTPUT:1: rect=2, square=1 | square=4, square=1 | rect=12, square=1 | square=16, square=1
% OUTPUT-NEXT:2: square=4, square=1 | rect=12, square=1 | square=16, square=1 | rect=30, square=1
% OUTPUT-NEXT:3: rect=12, square=1 | square=16, square=1 | rect=30, square=1 | square=36, square=1
% OUTPUT-NEXT:4: square=16, square=1 | rect=30, square=1 | square=36, square=1 | rect=56, square=1
