% OUTPUT:3
% OUTPUT-NOT:{{.}}

:- module run_if_some_scope.
:- interface.
:- import_module io.
:- pred main(io::di, io::uo) is det.
:- implementation.
:- import_module int, list, string.

main(!IO) :-
    ( if some [V] (V = 3, list.member(V, [3, 4])) then io.write_int(V, !IO) else true ),
    io.nl(!IO).
