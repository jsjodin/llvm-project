% io.write's quoting of constructor names, which of them are operators, and how
% literals and operator atoms are written as operands.
% The expected output is mmc's for the same program.
%
% RUN: merkc %s -o %t && %t | diff %S/Inputs/io-write-names.expected -
% RUN: env MERK_HEAP_CHUNK_BYTES=64 %t | diff %S/Inputs/io-write-names.expected -
% RUN: merkc -O2 %s -o %t2 && %t2 | diff %S/Inputs/io-write-names.expected -

:- module io_write_names.
:- interface.
:- import_module io.
:- pred main(io::di, io::uo) is det.
:- implementation.
:- import_module list.
:- type a ---> (plain) ; (a1_B) ; (aB) ; ('A') ; ('_x') ; ('1a') ; ('é') ; ('aé') ; ('') ; ('a b') ; ('a\nb') ; ('a\'b') ; ('a"b') ; ('a\\b') ; ('+++') ; ('#') ; ('<->') ; ('$') ; ('~') ; ('?') ; ('`') ; ('@@') ; ('\\\\') ; ('/') ; ('%') ; ('/*') ; ('(') ; (')') ; ('[') ; (']') ; ('{') ; ('}') ; ('.') ; ('|') ; ('x.y') ; ('\t') ; ('a\x01\b') ; ('\x7f\') ; ('😀') ; ('!') ; ('!!') ; ('not') ; ('div') ; ('mod') ; ('a-b') ; (';;') ; (',,') ; ('+') ; ('-') ; ('*') ; ('\\') ; ('=').
:- type b ---> x ; y ; ('+') ; ('-') ; (not) ; (*) ; [] ; {} ; f(b) ; g(b, b) ; [b | b] ; {b, b} ; (b + b) ; (b - b) ; (b * b) ; (b = b) ; (b or b) ; (b -> b) ; (not b) ; - b ; + b ; \ b ; \+ b ; n(int) ; fl(float) ; st(string) ; ch(character) ; c1(int, int) ; (int ** b) ; (float // b) ; (string /\ b).
:- pred wa(a::in, io::di, io::uo) is det.
wa(X, !IO) :- io.write(X, !IO),
    io.nl(!IO).
:- pred w(b::in, io::di, io::uo) is det.
w(X, !IO) :- io.write(X, !IO),
    io.nl(!IO).
main(!IO) :-
    wa(plain, !IO),
    wa(a1_B, !IO),
    wa(aB, !IO),
    wa(('A'), !IO),
    wa(('_x'), !IO),
    wa(('1a'), !IO),
    wa(('é'), !IO),
    wa(('aé'), !IO),
    wa((''), !IO),
    wa(('a b'), !IO),
    wa(('a\nb'), !IO),
    wa(('a\'b'), !IO),
    wa(('a"b'), !IO),
    wa(('a\\b'), !IO),
    wa(('+++'), !IO),
    wa(('#'), !IO),
    wa(('<->'), !IO),
    wa(('$'), !IO),
    wa(('~'), !IO),
    wa(('?'), !IO),
    wa(('`'), !IO),
    wa(('@@'), !IO),
    wa(('\\\\'), !IO),
    wa(('/'), !IO),
    wa(('%'), !IO),
    wa(('/*'), !IO),
    wa(('('), !IO),
    wa((')'), !IO),
    wa(('['), !IO),
    wa((']'), !IO),
    wa(('{'), !IO),
    wa(('}'), !IO),
    wa(('.'), !IO),
    wa(('|'), !IO),
    wa(('x.y'), !IO),
    wa(('\t'), !IO),
    wa(('a\x01\b'), !IO),
    wa('\x7f\', !IO),
    wa(('😀'), !IO),
    wa(('!'), !IO),
    wa(('!!'), !IO),
    wa(('not'), !IO),
    wa(('div'), !IO),
    wa(('mod'), !IO),
    wa(('a-b'), !IO),
    wa((';;'), !IO),
    wa((',,'), !IO),
    wa(('+'), !IO),
    wa(('-'), !IO),
    wa(('*'), !IO),
    wa(('\\'), !IO),
    wa(('='), !IO),
    % atom operators as arguments and operands
    w(f((+)), !IO),
    w(g((-), (not)), !IO),
    w((+) + (+), !IO),
    w(x + (-), !IO),
    w(- ((+)), !IO),
    w(- x, !IO),
    w(not x, !IO),
    w(not ((+)), !IO),
    w(not not x, !IO),
    w(not (x or y), !IO),
    w(\+ not x, !IO),
    w(\ (not x), !IO),
    w([(+) | (-)], !IO),
    w([x | []], !IO),
    w([x, y | []], !IO),
    w([x | y], !IO),
    w([x, y | x], !IO),
    w([not x | not y], !IO),
    w({(+), (-)}, !IO),
    w({x or y, x}, !IO),
    w([x or y], !IO),
    w([x or y | y], !IO),
    w(f(x or y), !IO),
    w(f(x -> y), !IO),
    w(f(x + y), !IO),
    w(f(not x), !IO),
    w(g(x = y, x - y), !IO),
    % literals in operators
    w(n(1) + n(2), !IO),
    w(n(-1) + n(-2), !IO),
    w(- n(-1), !IO),
    w(-1 ** x, !IO),
    w(1 ** x, !IO),
    w(-1.5 // x, !IO),
    w(1.5 // x, !IO),
    w("s" /\ x, !IO),
    w(1 ** (2 ** x), !IO),
    w(-1 ** (-2 ** x), !IO),
    w(c1(-1, -2), !IO),
    w(fl(-1.0), !IO),
    w(st("s"), !IO),
    w(ch('x'), !IO),
    w(ch('+'), !IO),
    w(ch('='), !IO),
    w(ch('['), !IO),
    w(ch('a'), !IO),
    w(- (- x), !IO),
    w(- (+ x), !IO),
    w(\ (\ x), !IO),
    w(\+ (\+ x), !IO),
    w(x - (- y), !IO),
    w(x - (+ y), !IO),
    w(x * (- y), !IO),
    w((- x) * y, !IO),
    w((- x) - y, !IO),
    w(- (x - y), !IO),
    w(- (x * y), !IO),
    w(- f(x), !IO),
    w(- [x | y], !IO),
    w(x - [x | y], !IO),
    w([] - x, !IO),
    w({} - x, !IO),
    w(- [], !IO),
    w(- {}, !IO),
    wch('+', !IO),
    io.nl(!IO), wch('=', !IO),
    io.nl(!IO), wch('[', !IO),
    io.nl(!IO), wch('a', !IO),
    io.nl(!IO), wch('.', !IO),
    io.nl(!IO), wch(',', !IO),
    io.nl(!IO), wch('|', !IO),
    io.nl(!IO), wch(';', !IO),
    io.nl(!IO), wch('!', !IO),
    io.nl(!IO), wch('%', !IO),
    io.nl(!IO), wch('_', !IO),
    io.nl(!IO), wch('A', !IO),
    io.nl(!IO),
    io.write("\a\b\f\n\r\t\v", !IO),
    io.nl(!IO), wch('\a', !IO),
    io.nl(!IO), wch('\b', !IO),
    io.nl(!IO), wch('\f', !IO),
    io.nl(!IO), wch('\r', !IO),
    io.nl(!IO), wch('\v', !IO),
    io.nl(!IO), io.write('\x80\', !IO),
    io.nl(!IO), io.write('\xa0\', !IO),
    io.nl(!IO), io.write('\xad\', !IO),
    io.nl(!IO), io.write("\x80\\xa0\\xad\", !IO),
    io.nl(!IO), io.write('\x1f\', !IO),
    io.nl(!IO), io.write('\x100\', !IO),
    io.nl(!IO), io.write('\xfeff\', !IO),
    io.nl(!IO), io.write('\x2028\', !IO),
    io.nl(!IO), io.write('\x10ffff\', !IO),
    io.nl(!IO).

:- pred wch(character::in, io::di, io::uo) is det.
wch(C, !IO) :- io.write(C, !IO).
